export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((project) => project.slug === slug)
}

export function getProjectsBySlugs(slugs: string[]): Project[] {
  return slugs.map((slug) => getProjectBySlug(slug)).filter((p): p is Project => Boolean(p))
}

export const featuredProjects = projects.filter((project) => project.featured)

export function nextProject(slug: string): Project {
  const index = projects.findIndex((project) => project.slug === slug)
  return projects[(index + 1) % projects.length]
}

export const categoriesInUse = (Object.keys(categoryLabels) as ProjectCategory[]).filter((category) =>
  projects.some((project) => project.category === category),
)

/** Up to `limit` projects of a category, excluding one slug — used for related work. */
export function relatedProjects(category: ProjectCategory, exclude: string, limit = 2): Project[] {
  return projects.filter((p) => p.category === category && p.slug !== exclude).slice(0, limit)
}
